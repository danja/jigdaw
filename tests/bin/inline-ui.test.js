// tests/bin/inline-ui.test.js
//
// bin/inline-ui.js writes the bridge into an editor page. A page that is out of date with it, or that has
// the bridge more or less than once, is an editor running code the digest was not computed over.
import { describe, it, expect } from 'vitest'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, readdirSync, existsSync, symlinkSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { inlineBridge, bridgeSource, buildUi, MARKER } from '../../bin/inline-ui.js'

const root = resolve(import.meta.dirname, '../..')

describe('inlineBridge', () => {
  it('replaces the marker with one script that defines jig', async () => {
    const out = await inlineBridge(`<body>${MARKER}</body>`)
    expect(out).not.toContain('data-jig-bridge')
    expect(out).toContain('const jig = createBridge(')
    expect(out.match(/<script>/g)).toHaveLength(1)
  })

  it('leaves no module syntax behind, which a classic script cannot parse', async () => {
    const source = await bridgeSource()
    expect(source).not.toMatch(/^\s*(import|export)\s/m)
    expect(() => new Function('window', 'document', 'parent', source)).not.toThrow()
  })

  it('refuses a page with no marker, and one with two', async () => {
    await expect(inlineBridge('<body></body>')).rejects.toThrow(/exactly once.*0 times/)
    await expect(inlineBridge(`${MARKER}${MARKER}`)).rejects.toThrow(/2 times/)
  })
})

describe('buildUi', () => {
  it('writes ui/index.html with the generated note after the doctype', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'inline-ui-'))
    try {
      mkdirSync(join(dir, 'ui'))
      writeFileSync(join(dir, 'ui/src.html'), `<!doctype html>\n<html><body>${MARKER}</body></html>`)
      await buildUi(dir)
      const html = readFileSync(join(dir, 'ui/index.html'), 'utf8')
      expect(html.startsWith('<!doctype html>')).toBe(true)
      expect(html).toContain('GENERATED by bin/inline-ui.js')
    } finally { rmSync(dir, { recursive: true }) }
  })

  it('does its work when run through a symlink to the script, not nothing with exit 0', () => {
    const dir = mkdtempSync(join(tmpdir(), 'inline-ui-'))
    try {
      mkdirSync(join(dir, 'ui'))
      writeFileSync(join(dir, 'ui/src.html'), `<!doctype html>\n<html><body>${MARKER}</body></html>`)
      symlinkSync(join(root, 'bin/inline-ui.js'), join(dir, 'link.js'))
      const run = spawnSync('node', [join(dir, 'link.js'), dir], { encoding: 'utf8' })
      expect(run.status).toBe(0)
      expect(existsSync(join(dir, 'ui/index.html'))).toBe(true)
    } finally { rmSync(dir, { recursive: true }) }
  })

  it('exits non-zero and writes nothing when the page has no marker', () => {
    const dir = mkdtempSync(join(tmpdir(), 'inline-ui-'))
    try {
      mkdirSync(join(dir, 'ui'))
      writeFileSync(join(dir, 'ui/src.html'), '<html></html>')
      const run = spawnSync('node', [join(root, 'bin/inline-ui.js'), dir], { encoding: 'utf8' })
      expect(run.status).toBe(1)
      expect(run.stderr).toMatch(/exactly once/)
      expect(existsSync(join(dir, 'ui/index.html'))).toBe(false)
    } finally { rmSync(dir, { recursive: true }) }
  })
})

// Every committed editor with a src.html is current: rebuilt from it, it is byte for byte what is on disk.
describe('committed editors', () => {
  const plugins = readdirSync(join(root, 'plugins')).filter(n => existsSync(join(root, 'plugins', n, 'ui/src.html')))

  it('are found', () => { expect(plugins).toContain('dynamix') })

  for (const name of plugins) {
    it(`${name}/ui/index.html is what inline-ui makes of src.html`, async () => {
      const dir = mkdtempSync(join(tmpdir(), 'inline-ui-'))
      try {
        mkdirSync(join(dir, 'ui'))
        writeFileSync(join(dir, 'ui/src.html'), readFileSync(join(root, 'plugins', name, 'ui/src.html')))
        await buildUi(dir)
        // The generated note carries the directory's name, so build under that name.
        const expected = readFileSync(join(dir, 'ui/index.html'), 'utf8').replace(/Do not edit: [^/]+\//, `Do not edit: ${name}/`)
        expect(readFileSync(join(root, 'plugins', name, 'ui/index.html'), 'utf8')).toBe(expected)
      } finally { rmSync(dir, { recursive: true }) }
    })
  }
})
