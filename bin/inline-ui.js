// bin/inline-ui.js
//
// Builds a plugin's editor page: ui/src.html with the page-side bridge (src/plugin-ui/JigUi.js and the unit
// text it shares with the generated panel) written into it as one inline script.
//
// Inline because a plugin's jig:integrity digest covers one file, and an editor is code a host runs in a
// frame: a script fetched separately would be code the digest does not cover (contract section 9.1).
//
//   node bin/inline-ui.js plugins/dynamix      reads plugins/dynamix/ui/src.html, writes ui/index.html
//
// src.html marks where the bridge goes with `<script data-jig-bridge></script>`. The bridge defines `jig`.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { isMain } from './is-main.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// In dependency order. Each is an ES module whose imports are all among the others.
const MODULES = ['src/ui/PortText.js', 'src/ui/Dial.js', 'src/plugin-ui/JigUi.js']

export const MARKER = '<script data-jig-bridge></script>'

/** The bridge as one script body: the modules without their import and export keywords, then the call. */
export async function bridgeSource () {
  const parts = []
  for (const file of MODULES) {
    const text = await readFile(join(root, file), 'utf8')
    parts.push(text
      .split('\n')
      .filter(line => !/^import\s.*from\s/.test(line))
      .map(line => line.replace(/^export\s+/, ''))
      .join('\n'))
  }
  parts.push('const jig = createBridge({ window, document, parent })')
  const source = parts.join('\n')
  // A script that contains this ends the element early and the rest of it becomes markup.
  if (/<\/script/i.test(source)) throw new Error('the bridge contains a closing script tag, which cannot be inlined')
  return source
}

/** `html` with the marker replaced by the bridge. Throws unless the marker occurs exactly once. */
export async function inlineBridge (html) {
  const count = html.split(MARKER).length - 1
  if (count !== 1) throw new Error(`ui/src.html must contain ${MARKER} exactly once, and has it ${count} times`)
  const script = `<script>\n${await bridgeSource()}\n</script>`
  return html.replace(MARKER, () => script)
}

export async function buildUi (pluginDir) {
  const source = await readFile(join(pluginDir, 'ui/src.html'), 'utf8')
  const built = await inlineBridge(source)
  const name = pluginDir.split('/').filter(Boolean).pop()
  // After the doctype, so the page stays in standards mode.
  const note = `<!-- GENERATED by bin/inline-ui.js from ui/src.html. Do not edit: ${name}/ui/index.html is the file the digest covers. -->`
  const out = built.replace(/^(<!doctype html>\s*)/i, `$1${note}\n`)
  await writeFile(join(pluginDir, 'ui/index.html'), out)
  return out.length
}

if (isMain(import.meta.url)) {
  const dir = process.argv[2]
  if (!dir) {
    console.error('usage: node bin/inline-ui.js PLUGIN_DIR')
    process.exit(2)
  }
  try {
    const size = await buildUi(resolve(dir))
    console.log(`wrote ${dir}/ui/index.html, ${size} bytes`)
  } catch (error) {
    console.error(`inline-ui: ${error.message}`)
    process.exit(1)
  }
}
