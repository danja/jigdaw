// bin/build-precache.js
//
// The list of files the service worker keeps for offline use, with a hash of each
// and a version that is the hash of all of them: web/precache.js. A new version is
// a new cache, so a changed file reaches people without anyone remembering to bump
// a number, and an unchanged build changes nothing.
//
// Committed like the bundle, since the server has no build step. A test recomputes
// it and fails when the committed file is stale, which is how a shell that lists a
// file that is gone, or misses one that was added, gets noticed.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { dirname, resolve, join } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * The shell, as [servedPath, fileOnDisk] pairs. Paths are relative to the
 * worker's scope. The shapes are fetched by the page at start, so they are part of it.
 */
export function shellFiles () {
  const web = name => [name, join('web', name)]
  const inDir = (dir, keep) => readdirSync(resolve(root, 'web', dir)).filter(keep).sort().map(f => [`${dir}/${f}`, join('web', dir, f)])
  return [
    ['./', 'web/index.html'],
    web('app.bundle.js'),
    web('simple.html'),
    web('view.js'),
    web('simple.bundle.js'),
    web('reel.html'),
    web('reel.bundle.js'),
    web('panel.css'),
    web('script.css'),
    web('host.json'),
    web('manifest.webmanifest'),
    ['vocabs/shapes.ttl', 'vocabs/shapes.ttl'],
    ...inDir('icons', f => f.endsWith('.png')),
    ...inDir('presets', f => f.endsWith('.ttl') || f === 'index.json')
  ]
}

export function buildPrecache () {
  const files = shellFiles().map(([path, disk]) => ({
    path,
    hash: createHash('sha256').update(readFileSync(resolve(root, disk))).digest('hex').slice(0, 16)
  }))
  const version = createHash('sha256').update(files.map(f => `${f.path}:${f.hash}`).join('\n')).digest('hex').slice(0, 12)
  return `// web/precache.js\n// Generated by bin/build-precache.js. Do not edit: npm run build:precache.\nself.APP_PRECACHE = ${JSON.stringify({ version, files }, null, 2)}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(resolve(root, 'web/precache.js'), buildPrecache())
  console.log(`web/precache.js: ${shellFiles().length} files`)
}
