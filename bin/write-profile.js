// bin/write-profile.js
//
// Generate a plugin's profile.ttl with the digests of the files on disk.
//
// A digest written by hand goes stale on the next build, silently, and the
// symptom is a plugin the host refuses with an integrity mismatch. Generating
// it means the profile always describes the artefacts that exist.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, basename, dirname, relative } from 'node:path'
import { digestOf } from '../src/host/Integrity.js'

const dir = resolve(process.argv[2] ?? '.')
const template = JSON.parse(await readFile(resolve(dir, 'profile.json'), 'utf8'))

async function digestFor (file) {
  return digestOf(new Uint8Array(await readFile(resolve(dir, file))))
}

const resources = {}
for (const [key, file] of Object.entries(template.resources)) {
  resources[key] = { file, integrity: await digestFor(file) }
}

// jig:module: optional (vocabs/shapes.ttl warns rather than refuses its
// absence), for a plugin whose processing is plain JavaScript. Everything
// below that touches resources.module guards on this the same way.
const hasModule = Boolean(resources.module)

// jig:ui: optional, a plugin's own editor, loaded by a host into a sandboxed
// cross-origin frame (contract section 9.1). One file, so the digest covers
// all of it: a frame's document cannot be integrity checked by the browser the
// way a script can, and a page that loaded further scripts of its own would be
// running code this digest says nothing about.
const hasUi = Boolean(resources.ui)

// jig:asset: any further file beyond the module and the processor, such as
// the compiled bytecode a converted JSFX plugin's script lives in
// (bin/jsfx-import.js). Optional and plural, unlike module and processor,
// so it stays a separate list rather than another key in template.resources.
const assets = []
for (const asset of template.assets ?? []) {
  assets.push({ ...asset, integrity: await digestFor(asset.file) })
}

// jig:skin: optional, a declarative interface (docs/svg-skins.md). The skin
// document names the artwork and carries its digest, and the profile carries the
// skin's, so redrawing the artwork changes those two files and not this one's
// other contents. Both are generated here for the same reason as the rest:
// a digest written by hand goes stale.
const SKIN_CLASS = { rotary: 'RotaryControl', linear: 'LinearControl', toggle: 'ToggleControl', selector: 'SelectorControl', readout: 'ReadoutControl' }
const skin = template.skin
if (skin) {
  const artwork = { file: skin.artwork, integrity: await digestFor(skin.artwork) }
  const out = []
  const sw = s => out.push(s)
  sw(`# ${basename(dir)}/${skin.file}`)
  sw('#')
  sw('# GENERATED by bin/write-profile.js from the "skin" key of profile.json. Do not edit:')
  sw('# the artwork digest is of the file on disk.')
  sw('')
  sw(`@base <${new URL(skin.file, template.iri).href}> .`)
  sw('@prefix jig: <http://purl.org/stuff/jigdaw/> .')
  sw('')
  sw('<>')
  sw('    jig:artwork <#artwork> ;')
  sw(`    jig:control ${skin.controls.map(c => `<#${c.id}>`).join(' , ')} .`)
  sw('')
  sw('<#artwork>')
  sw('    a jig:Artwork ;')
  sw(`    jig:location <${relative(dirname(skin.file), skin.artwork)}> ;`)
  sw('    jig:mediaType "image/svg+xml" ;')
  sw(`    jig:integrity "${artwork.integrity}" .`)
  for (const c of skin.controls) {
    const cls = SKIN_CLASS[c.kind]
    if (!cls) throw new Error(`skin control ${c.id}: unknown kind "${c.kind}"`)
    sw('')
    sw(`<#${c.id}>`)
    sw(`    a jig:${cls} ;`)
    sw(`    jig:boundSymbol ${JSON.stringify(c.port)} ;`)
    sw(`    jig:element ${JSON.stringify(c.element)}${c.kind === 'rotary' || c.kind === 'linear' || c.hit ? ' ;' : ' .'}`)
    if (c.hit) sw(`    jig:hitElement ${JSON.stringify(c.hit)}${c.kind === 'rotary' || c.kind === 'linear' ? ' ;' : ' .'}`)
    if (c.kind === 'rotary') {
      if (c.pivot) sw(`    jig:pivotElement ${JSON.stringify(c.pivot)} ;`)
      sw(`    jig:angleMin ${c.angleMin} ; jig:angleMax ${c.angleMax} .`)
    }
    if (c.kind === 'linear') sw(`    jig:trackElement ${JSON.stringify(c.track)} .`)
  }
  const text = out.join('\n') + '\n'
  await writeFile(resolve(dir, skin.file), text)
  skin.integrity = await digestOf(new TextEncoder().encode(text))
  skin.artworkIntegrity = artwork.integrity
}

const lines = []
const w = s => lines.push(s)

w(`# ${basename(dir)}/profile.ttl`)
w('#')
w('# GENERATED by bin/write-profile.js. Do not edit: the digests are of the')
w('# files on disk, and editing them by hand is how a profile comes to describe')
w('# artefacts that no longer exist. Edit profile.json and run ./build.sh.')
w('')
w(`@base <${template.iri}> .`)
w('')
w('@prefix jig:   <http://purl.org/stuff/jigdaw/> .')
w('@prefix trn:   <http://purl.org/stuff/transmissions/> .')
w('@prefix pu:    <http://purl.org/stuff/plugin-universe/> .')
w('@prefix lv2:   <http://lv2plug.in/ns/lv2core#> .')
w('@prefix midi:  <http://lv2plug.in/ns/ext/midi#> .')
w('@prefix units: <http://lv2plug.in/ns/extensions/units#> .')
// Only where it is used, so a profile that sets no priority is written exactly as it always was.
if (template.ports.some(p => p.displayPriority !== undefined)) w('@prefix pprops: <http://lv2plug.in/ns/ext/port-props#> .')
w('@prefix rdf:   <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .')
w('@prefix doap:  <http://usefulinc.com/ns/doap#> .')
w('@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .')
w('@prefix foaf:  <http://xmlns.com/foaf/0.1/> .')
w('')
w('<>')
w('    a jig:WebPlugin , trn:PluginProfile ;')
w(`    rdfs:label ${JSON.stringify(template.label)} ;`)
w(`    rdfs:comment ${JSON.stringify(template.comment)} ;`)
w(`    trn:vendor ${JSON.stringify(template.vendor)} ;`)
// Optional in the profile and required by anything packaging the plugin for a
// format that demands a version. bin/wam.js refuses a plugin without one.
if (template.version) w(`    doap:revision ${JSON.stringify(template.version)} ;`)
if (template.developer) w(`    doap:developer <${template.developer}> ;`)
w('    foaf:homepage <> ;')
w(`    trn:role ${template.roles.join(' , ')} ;`)
if (template.accepts?.length) w(`    trn:accepts ${template.accepts.join(' , ')} ;`)
w(`    trn:produces ${template.produces.join(' , ')} ;`)
if (template.genres?.length) w(`    trn:genre ${template.genres.map(g => JSON.stringify(g)).join(' , ')} ;`)
for (const caution of template.cautions ?? []) w(`    trn:caution ${JSON.stringify(caution)} ;`)
if (template.format) w(`    trn:format ${template.format} ;`)
if (template.licenceId) w(`    pu:licenceId ${JSON.stringify(template.licenceId)} ;`)
for (const c of template.requires ?? []) w(`    trn:requires ${c} ;`)
for (const c of template.prefers ?? []) w(`    jig:prefers ${c} ;`)
w('')
for (const [key, value] of Object.entries(template.shape)) w(`    jig:${key} ${value} ;`)
w('')
if (hasModule) w('    jig:module <#module> ;')
w('    jig:processor <#processor> ;')
if (hasUi) w('    jig:ui <#ui> ;')
if (skin) w('    jig:skin <#skin> ;')
// A skin's two files are also listed as assets, which is what jig:asset is for: a bundle, a verifier
// and an offline copy know a plugin is complete by walking this list, and the artwork is named only
// inside skin.ttl, where none of them look.
const listed = [...assets.map(a => `<#${a.key}>`), ...(skin ? ['<#skin>', '<#skin-artwork>'] : [])]
if (listed.length > 0) w(`    jig:asset ${listed.join(' , ')} ;`)
w('')
const pads = template.pads ?? []
if (pads.length === 0) {
  w(`    lv2:port ${template.ports.map(p => `<#${p.symbol}>`).join(' , ')} .`)
} else {
  w(`    lv2:port ${template.ports.map(p => `<#${p.symbol}>`).join(' , ')} ;`)
  w(`    jig:pad ${pads.map(pad => `<#${pad.id}>`).join(' , ')} .`)
}
w('')
if (hasModule) {
  w('<#module>')
  w('    a jig:Module ;')
  w(`    jig:location <${resources.module.file}> ;`)
  w('    jig:mediaType "application/wasm" ;')
  // A declared ABI is what lets a host without a JavaScript engine load the
  // module directly, skipping the processor. See docs/module-abi.md.
  if (template.abi) w(`    jig:abi ${template.abi} ;`)
  // Contract section 2.1: a host refuses a module needing a feature its
  // engine lacks, so the build that turned the feature on must say so.
  if (template.wasmFeatures?.length) w(`    jig:wasmFeature ${template.wasmFeatures.join(' , ')} ;`)
  w(`    jig:integrity "${resources.module.integrity}" .`)
  w('')
}
w('<#processor>')
w('    a jig:Processor ;')
w(`    jig:location <${resources.processor.file}> ;`)
w('    jig:mediaType "text/javascript" ;')
w(`    jig:registeredName ${JSON.stringify(template.registeredName)} ;`)
w(`    jig:integrity "${resources.processor.integrity}" .`)

if (hasUi) {
  w('')
  w('<#ui>')
  w('    a jig:UserInterface ;')
  w(`    jig:location <${resources.ui.file}> ;`)
  w('    jig:mediaType "text/html" ;')
  w(`    jig:integrity "${resources.ui.integrity}" .`)
}

if (skin) {
  w('')
  w('<#skin>')
  w('    a jig:Skin ;')
  w(`    jig:location <${skin.file}> ;`)
  w('    jig:mediaType "text/turtle" ;')
  w(`    jig:integrity "${skin.integrity}" .`)
  w('')
  w('<#skin-artwork>')
  w('    a jig:Resource ;')
  w(`    jig:location <${skin.artwork}> ;`)
  w('    jig:mediaType "image/svg+xml" ;')
  w(`    jig:integrity "${skin.artworkIntegrity}" .`)
}

// A pad is a named pair of this plugin's own ports; the panel draws it as a square the pointer drags across. Checked here so a pad that
// names a port the profile does not have is an error in the build, not a pad that moves nothing.
for (const pad of pads) {
  for (const axis of ['x', 'y']) {
    if (!template.ports.some(p => p.symbol === pad[axis])) throw new Error(`pad ${pad.id}: ${axis} names ${pad[axis]}, which is not a port of this plugin`)
  }
  w('')
  w(`<#${pad.id}>`)
  w('    a jig:ControlPad ;')
  w(`    rdfs:label ${JSON.stringify(pad.label)} ;`)
  const extras = []
  if (pad.choice) {
    if (!template.ports.some(p => p.symbol === pad.choice)) throw new Error(`pad ${pad.id}: choice names ${pad.choice}, which is not a port of this plugin`)
    extras.push(`jig:padChoice <#${pad.choice}>`)
  }
  for (const [key, term] of [['xLow', 'padXLow'], ['xHigh', 'padXHigh'], ['yLow', 'padYLow'], ['yHigh', 'padYHigh']]) {
    if (pad[key]) extras.push(`jig:${term} ${JSON.stringify(pad[key])}`)
  }
  w(`    jig:padX <#${pad.x}> ;`)
  w(`    jig:padY <#${pad.y}>${extras.length > 0 ? ' ;' : ' .'}`)
  extras.forEach((line, i) => w(`    ${line}${i === extras.length - 1 ? ' .' : ' ;'}`))
}

for (const asset of assets) {
  w('')
  w(`<#${asset.key}>`)
  w('    a jig:Resource ;')
  w(`    jig:location <${asset.file}> ;`)
  if (asset.mediaType) w(`    jig:mediaType ${JSON.stringify(asset.mediaType)} ;`)
  if (asset.userReplaceable) w(`    jig:userReplaceable true ;`)
  if (asset.maxBytes) w(`    jig:maxBytes ${asset.maxBytes} ;`)
  w(`    jig:integrity "${asset.integrity}" .`)
}

for (const port of template.ports) {
  w('')
  w(`<#${port.symbol}>`)
  w('    a lv2:InputPort , lv2:ControlPort ;')
  w(`    lv2:symbol ${JSON.stringify(port.symbol)} ; lv2:name ${JSON.stringify(port.name)} ;`)
  let line = `    lv2:default ${port.default} ; lv2:minimum ${port.minimum} ; lv2:maximum ${port.maximum}`
  // Required when the module declares an ABI: a native host has no processor
  // holding the symbol to index mapping, and position in this file is a
  // property of the document rather than of the module.
  if (port.paramIndex !== undefined) line += ` ;\n    jig:paramIndex ${port.paramIndex}`
  // Audio-rate parameters cost a Float32Array per quantum whether or not
  // anything modulates them, so k-rate is the default and a-rate is declared
  // per port, for parameters meant to be audio-modulated (contract 5.2).
  if (port.automationRate === 'a-rate') line += ' ;\n    jig:automationRate jig:ARate'
  // The panel section this control belongs under. A plain label: groups are
  // per-plugin display hints, never addressed across documents.
  if (port.group) line += ` ;\n    jig:controlGroup ${JSON.stringify(port.group)}`
  // One plain sentence saying what the control does: the panel shows it on hover and focus, and a screen reader reads it on focus.
  if (port.comment) line += ` ;\n    rdfs:comment ${JSON.stringify(port.comment)}`
  // How much the author says this control matters, for a panel that shows the few first. Higher is more important.
  if (port.displayPriority !== undefined) line += ` ;\n    pprops:displayPriority ${port.displayPriority}`
  if (port.unit) line += ` ;\n    units:unit units:${port.unit}`
  if (port.toggled) line += ' ;\n    lv2:portProperty lv2:toggled'
  if (port.scalePoints) {
    line += ' ;\n    lv2:portProperty lv2:enumeration ;\n    lv2:scalePoint\n'
    line += port.scalePoints
      .map((sp, i) => `        <#${port.symbol}-${i}>`)
      .join(' ,\n')
  }
  // A MIDI controller driving this port, as LV2's own MIDI extension has it:
  // the port binds a midi:Controller carrying the controller number. The
  // binding is skolemised under the port for the same reason a scale point
  // is: a hyphen cannot appear in an lv2:symbol, so this cannot collide.
  if (port.controller !== undefined) line += ` ;\n    midi:binding <#${port.symbol}-cc>`
  w(`${line} .`)

  // Skolemised, not blank. AGENTS.md forbids a blank node for anything
  // addressable, and a scale point is addressable: it is what a selector's
  // options are generated from. It is also what made the first attempt at
  // signing a profile fail, because a blank node has no stable name and so no
  // canonical form. A hyphen cannot appear in an lv2:symbol, which is why this
  // cannot collide with a port.
  for (const [i, sp] of (port.scalePoints ?? []).entries()) {
    w('')
    w(`<#${port.symbol}-${i}> rdfs:label ${JSON.stringify(sp.label)} ; rdf:value ${sp.value} .`)
  }

  if (port.controller !== undefined) {
    w('')
    w(`<#${port.symbol}-cc> a midi:Controller ; midi:controllerNumber ${port.controller} .`)
  }
}

const output = lines.join('\n') + '\n'
await writeFile(resolve(dir, 'profile.ttl'), output)
console.log(`wrote ${resolve(dir, 'profile.ttl')}`)
