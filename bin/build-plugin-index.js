// bin/build-plugin-index.js
//
// Generate plugins/index.json and web/collections/jigdaw.ttl from the
// profiles on disk.
//
// plugins/index.json is what the server reads, which keeps bin/serve.js to
// node builtins alone: no npm install on the server, no dependency tree to
// keep current there, and nothing to go wrong at start-up except the code
// itself.
//
// That property was broken once by importing an RDF parser into the server,
// which crashed it on a deployment that had no node_modules and took the site
// down with a 502. tests/docs/conventions.test.js now fails if anything
// reachable from bin/serve.js imports a package again.
//
// web/collections/jigdaw.ttl is generated for the reason docs/plugin-collections.md
// gives for keeping a collection and its profiles in step: hand-editing a list
// of names beside a directory of profiles is exactly the shape of drift
// AGENTS.md warns about. tests/catalogue/CollectionLoader.test.js still checks
// the generated file against plugins/ on disk, so a generator with a bug is
// still caught, just no longer the only thing standing between the two.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve, join } from 'node:path'
import { parseText } from '../src/rdf/parse.js'
import { readProfile } from '../src/rdf/ProfileReader.js'
import { compactTerm } from '../src/catalogue/facets.js'
import { pluginDirs } from '../src/catalogue/PluginDirectories.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'plugins')

const entries = []
const collectionMembers = []
const problems = []

for (const name of await pluginDirs(dir)) {
  const path = join(dir, name, 'profile.ttl')
  try {
    const profile = readProfile(await parseText(await readFile(path, 'utf8'), `file://${path}`))
    entries.push({
      iri: profile.iri,
      label: profile.label,
      comment: profile.comment,
      vendor: profile.vendor,
      homepage: profile.homepage ?? profile.iri,
      // Ours, so they run here by definition.
      web: true,
      local: true,
      roles: profile.roles.map(compactTerm),
      formats: profile.formats.map(compactTerm),
      accepts: profile.accepts.map(compactTerm),
      produces: profile.produces.map(compactTerm),
      requires: profile.requires.map(compactTerm),
      cautions: profile.cautions,
      parameters: profile.ports.map(p => p.symbol)
    })
    // Relative to web/collections/, so the collection names plugins served
    // beside it on whichever host serves it (plugin-collections.md section 1.1).
    collectionMembers.push({ relativeIri: `../plugins/${name}/`, label: profile.label })
  } catch (error) {
    problems.push(`${name}: ${error.message}`)
  }
}

entries.sort((a, b) => (a.label ?? '').localeCompare(b.label ?? ''))

const output = {
  generated: 'bin/build-plugin-index.js',
  note: 'Generated from each plugins/<name>/profile.ttl. Do not edit; run npm run build:index.',
  plugins: entries
}

await writeFile(join(dir, 'index.json'), JSON.stringify(output, null, 2) + '\n')

const collectionPath = join(root, 'web/collections/jigdaw.ttl')
await writeFile(collectionPath, renderCollection(collectionMembers))

if (problems.length > 0) console.warn('skipped:', problems.join('; '))
console.log(`plugins/index.json: ${entries.length} plugin(s) (${entries.map(e => e.label).join(', ')})`)
console.log(`web/collections/jigdaw.ttl: ${collectionMembers.length} plugin(s)`)

/** Render web/collections/jigdaw.ttl from the plugins found on disk, in the
 * form docs/plugin-collections.md section 1 requires. */
function renderCollection (members) {
  const lines = [
    '# web/collections/jigdaw.ttl',
    '#',
    '# Generated by bin/build-plugin-index.js (npm run build:index). Do not edit',
    '# by hand; add or remove a plugin under plugins/ instead.',
    '#',
    '# The plugins this host serves, as a collection (docs/plugin-collections.md).',
    '# It is the collection the page offers to open, and a worked example of one',
    '# published at a URL.',
    '#',
    '# There is no @base, unlike a profile, and that is deliberate: the plugins sit',
    '# beside this file on whichever host serves it, so <../plugins/pulse/> resolves',
    '# to the Pulse served by that same host, on localhost and on the live site',
    '# alike. A collection of other people\'s plugins names them absolutely.',
    '#',
    '# tests/catalogue/CollectionLoader.test.js fails if this list and plugins/',
    '# disagree, in either direction.',
    '',
    '@prefix jig:     <http://purl.org/stuff/jigdaw/> .',
    '@prefix rdfs:    <http://www.w3.org/2000/01/rdf-schema#> .',
    '@prefix dcterms: <http://purl.org/dc/terms/> .',
    '',
    '<>',
    '    a jig:PluginCollection ;',
    '    rdfs:label "JigDAW plugins" ;',
    '    rdfs:comment "Every plugin in the JigDAW repository: instruments, effects and the converted JSFX." ;',
    '    dcterms:hasPart',
    '        ' + members.map(m => `<${m.relativeIri}>`).join(' ,\n        ') + ' .',
    '',
    ...members.map(m => `<${m.relativeIri}> rdfs:label ${JSON.stringify(m.label)} .`)
  ]
  return lines.join('\n') + '\n'
}
